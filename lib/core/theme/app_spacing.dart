/// Spacing tokens for the Hisaab design system.
/// Based on a 4 px grid. Screen margin is always 16.
abstract final class AppSpacing {
  static const double xs4 = 4;
  static const double sm8 = 8;
  static const double md16 = 16;
  static const double lg20 = 20;
  static const double xl32 = 32;

  /// Standard horizontal margin applied to all screens.
  static const double screenMargin = 16;
}
